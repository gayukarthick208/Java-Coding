package java_demo;
//check if the number is odd or even
public class odd_even {
	public static void main(String[] args) {
		int number = 55;
		System.out.println("Number: " + number);
		if (number % 2 == 0) {
			System.out.println("this is Even Number");

		} else {
			System.out.println("this is Odd Number");
		}
	}
}
