package Control;
//1.Check Positive or Negative - Write a program to check 

//whether a number is positive or negative using `if-else`. 

public class ifelse_statement {

	public static void main(String[] args) {
		int number = 2;

		if (number > 0) {
			System.out.println("Positive Number");
		}

		else {
			System.out.println("Negative Number");
		}

	}

}
