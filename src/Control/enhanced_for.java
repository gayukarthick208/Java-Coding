package Control;
//Enhanced for Loop: Write a program to print all elements of an array using an enhanced for loop
public class enhanced_for {
	public static void main(String[] args) {
		int[] numbers= {10,20,30,40,50};
		System.out.println("Print array elemnts:");
		for(int num:numbers) {
			System.out.println(num);
		}
		
	}

}
