package Control;
// Determine if a number is odd or even using the modulus operator
//and `if-else`.
public class even_odd {
	public static void main(String[] args) {
		int num = 75;
		if (num%2==0) {
			System.out.println("Even Number");
		}
		else {
			System.out.println("Odd Number");
		}
		
	}

}
