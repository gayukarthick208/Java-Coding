package Control;
//Write a program to print numbers from 1 to 10, but stop the loop if the number is 5
//using the break statement.
public class Jump_break {
	public static void main(String[] args) {
		int num= 10;
		for(int i=1;i<=num;i++) {
			if(i==5) {
			break;
			}
			
				System.out.println(i);
			}
	}
}
	

