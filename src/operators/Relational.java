package operators;

public class Relational {
	public static void main(String[] args) {
		int a=20;
		int b=10;
		System.out.println("value of a:"+a);
		System.out.println("value of b:"+b);
		System.out.println(a==b);
		System.out.println(a!=b);
		System.out.println(a>b);
		System.out.println(a<b);
		System.out.println(a>=b);
		System.out.println(a<=b);
	}

}
